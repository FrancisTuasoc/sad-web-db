ALTER TYPE app.payment_method
  ADD VALUE IF NOT EXISTS 'pay_at_shop';

ALTER TABLE app.orders
  ADD COLUMN IF NOT EXISTS delivery_fee NUMERIC(10, 2) DEFAULT 0 NOT NULL
    CHECK (delivery_fee >= 0),
  ADD COLUMN IF NOT EXISTS arrival_deadline TIMESTAMPTZ,
  ADD COLUMN IF NOT EXISTS contact_first_name VARCHAR(100) DEFAULT '' NOT NULL,
  ADD COLUMN IF NOT EXISTS contact_last_name VARCHAR(100) DEFAULT '' NOT NULL,
  ADD COLUMN IF NOT EXISTS contact_email VARCHAR(255) DEFAULT '' NOT NULL,
  ADD COLUMN IF NOT EXISTS contact_street VARCHAR(255) DEFAULT '' NOT NULL,
  ADD COLUMN IF NOT EXISTS contact_barangay VARCHAR(255) DEFAULT '' NOT NULL,
  ADD COLUMN IF NOT EXISTS contact_city VARCHAR(255) DEFAULT '' NOT NULL,
  ADD COLUMN IF NOT EXISTS contact_province VARCHAR(255) DEFAULT '' NOT NULL,
  ADD COLUMN IF NOT EXISTS contact_postal_code VARCHAR(4) DEFAULT '' NOT NULL,
  ADD COLUMN IF NOT EXISTS contact_address TEXT DEFAULT '' NOT NULL,
  ADD COLUMN IF NOT EXISTS cancelled_by VARCHAR(50);

ALTER TABLE app.order_items
  ADD COLUMN IF NOT EXISTS addon_quantity_mode app.addon_qty_mode
    DEFAULT 'per_item' NOT NULL;
